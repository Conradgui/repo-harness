@dataclass(frozen=True)
class CommandResult:
    args: tuple[str, ...]
    cwd: str
    returncode: int
    stdout: str
    stderr: str

    @property
    def ok(self) -> bool:
        return self.returncode == 0

    def combined(self) -> str:
        return (self.stdout + "\n" + self.stderr).strip()


