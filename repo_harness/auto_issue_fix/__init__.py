class GhCliBackend:
    def __init__(self, runner=None):
        self.runner = runner or run_command

    def issue_view(self, repo: str, issue: int) -> AutoIssueFixIssue:
        result = self.runner(
            [
                "gh",
                "issue",
                "view",
                str(issue),
                "--repo",
                normalize_repo(repo),
                "--json",
                "number,title,body,url,labels,state,assignees",
            ]
        )
        require_ok(result, "gh issue view failed")
        payload = json.loads(result.stdout or "{}")
        return issue_from_gh_payload(normalize_repo(repo), payload)

    def issue_list(self, repo: str, limit: int = 20) -> list[AutoIssueFixIssue]:
        result = self.runner(
            [
                "gh",
                "issue",
                "list",
                "--repo",
                normalize_repo(repo),
                "--state",
                "open",
                "--limit",
                str(limit),
                "--json",
                "number,title,body,url,labels,state,assignees",
            ]
        )
        require_ok(result, "gh issue list failed")
        return [issue_from_gh_payload(normalize_repo(repo), item) for item in json.loads(result.stdout or "[]")]

    def search_repos(self, query: str = "topic:python sort:stars-desc", limit: int = 10) -> list[str]:
        result = self.runner(
            ["gh", "search", "repos", query, "--limit", str(limit), "--json", "fullName"]
        )
        require_ok(result, "gh search repos failed")
        return [str(item.get("fullName", "")).strip() for item in json.loads(result.stdout or "[]") if item.get("fullName")]

    def default_branch(self, repo: str) -> str:
        result = self.runner(["gh", "repo", "view", normalize_repo(repo), "--json", "defaultBranchRef"])
        require_ok(result, "gh repo view failed")
        payload = json.loads(result.stdout or "{}")
        return str((payload.get("defaultBranchRef") or {}).get("name") or "main")

    def clone(self, repo: str, destination: Path) -> None:
        result = self.runner(["gh", "repo", "clone", normalize_repo(repo), str(destination)])
        require_ok(result, "gh repo clone failed")

    def ensure_fork_remote(self, cwd: Path) -> None:
        result = self.runner(
            ["gh", "repo", "fork", "--remote", "--remote-name", "fork", "--clone=false"],
            cwd=cwd,
        )
        if result.ok:
            return
        remotes = run_command(["git", "remote"], cwd=cwd)
        if "fork" in remotes.stdout.split():
            return
        require_ok(result, "gh repo fork failed")

    def current_user(self) -> str:
        result = self.runner(["gh", "api", "user", "--jq", ".login"])
        require_ok(result, "gh api user failed")
        return result.stdout.strip()

    def create_pr(self, repo: str, branch: str, title: str, body_file: Path, base: str) -> str:
        user = self.current_user()
        result = self.runner(
            [
                "gh",
                "pr",
                "create",
                "--repo",
                normalize_repo(repo),
                "--head",
                f"{user}:{branch}",
                "--base",
                base,
                "--title",
                title,
                "--body-file",
                str(body_file),
                "--draft",
            ]
        )
        require_ok(result, "gh pr create failed")
        return result.stdout.strip().splitlines()[-1].strip()


def redact_text(text: str) -> str:
    redacted = str(text)
    for pattern in SECRET_PATTERNS:
        redacted = pattern.sub("<redacted>", redacted)
    return redacted


def classify_github_error(text: str) -> str:
    lowered = str(text or "").lower()
    if any(pattern in lowered for pattern in GITHUB_BLOCKED_ERROR_PATTERNS):
        return "blocked_or_forbidden"
    return ""


def _contains_public_forbidden_term(text: str, term: str) -> bool:
    if " " in term or "-" in term:
        return term.lower() in text.lower()
    return re.search(rf"\b{re.escape(term)}\b", text, re.IGNORECASE) is not None


def maintainer_trust_block_reason(*, title: str, body: str, commit_message: str, branch: str) -> str:
    fields = {
        "title": title,
        "body": body,
        "commit message": commit_message,
        "branch": branch,
    }
    for field_name, value in fields.items():
        # Product naming will be revisited in a later rename pass. For now, keep
        # the existing internal branch prefix from blocking otherwise clean PRs.
        if field_name == "branch" and re.fullmatch(r"repo-harness-auto-issue-fix-\d+", str(value or "")):
            continue
        for term in PUBLIC_PR_BODY_FORBIDDEN_TERMS:
            if _contains_public_forbidden_term(str(value or ""), term):
                return f"maintainer trust gate blocked public {field_name} term: {term}"
    return ""


def normalize_repo(repo: str) -> str:
    value = str(repo or "").strip().removesuffix(".git").rstrip("/")
    if value.startswith("https://github.com/"):
        value = value[len("https://github.com/") :]
    if value.startswith("http://github.com/"):
        value = value[len("http://github.com/") :]
    if value.startswith("git@github.com:"):
        value = value[len("git@github.com:") :]
    return value


def run_command(args, cwd: Path | str | None = None, timeout: int = 300) -> CommandResult:
    cwd_text = str(Path(cwd).resolve()) if cwd else ""
    completed = subprocess.run(
        [str(item) for item in args],
        cwd=str(cwd) if cwd else None,
        text=True,
        capture_output=True,
        timeout=timeout,
        check=False,
    )
    return CommandResult(
        args=tuple(str(item) for item in args),
        cwd=cwd_text,
        returncode=int(completed.returncode),
        stdout=completed.stdout or "",
        stderr=completed.stderr or "",
    )


def require_ok(result: CommandResult, message: str) -> None:
    if result.ok:
        return
    command = " ".join(result.args)
    classification = classify_github_error(result.combined())
    if classification:
        raise RuntimeError(
            f"{message}: GitHub returned {classification}. "
            "Stop without retrying or bypassing; write fallback evidence instead.\n"
            f"{command}\n{result.combined()}"
        )
    raise RuntimeError(f"{message}: {command}\n{result.combined()}")


def issue_from_gh_payload(repo: str, payload: dict) -> AutoIssueFixIssue:
    labels = tuple(str(item.get("name", item)) for item in payload.get("labels", ()) if item)
    assignees = tuple(str(item.get("login", item)) for item in payload.get("assignees", ()) if item)
    return AutoIssueFixIssue(
        repo=normalize_repo(repo),
        number=int(payload.get("number") or 0),
        title=str(payload.get("title") or ""),
        body=str(payload.get("body") or ""),
        url=str(payload.get("url") or ""),
        labels=labels,
        state=str(payload.get("state") or "open"),
        assignees=assignees,
    )


def portable_path(path: str, placeholder: str, include_local_paths: bool = False) -> str:
    if include_local_paths:
        return redact_text(path)
    return placeholder


def default_run_id() -> str:
    return "auto_issue_fix_" + time.strftime("%Y%m%d_%H%M%S")


def default_evidence_dir(workspace_root: Path, run_id: str) -> Path:
    return workspace_root / ".repo-harness" / "auto-issue-fix" / run_id


def default_workdir(workspace_root: Path, run_id: str) -> Path:
    return workspace_root / ".repo-harness" / "auto-issue-fix-workspaces" / run_id


def _public_record(record: AutoIssueFixRunRecord, include_local_paths: bool) -> dict:
    data = asdict(record)
    data["workspace_path"] = portable_path(record.workspace_path, "<workspace>", include_local_paths)
    data["evidence_dir"] = portable_path(record.evidence_dir, "<evidence_dir>", include_local_paths)
    data["workdir"] = portable_path(record.workdir, "<workdir>", include_local_paths) if record.workdir else ""
    return json.loads(redact_text(json.dumps(data, ensure_ascii=False)))


def build_preview_review_gates(config: AutoIssueFixConfig, status: str) -> tuple[AutoIssueFixReviewGate, ...]:
    verdict = "pass" if status == "planned" else "block"
    action = (
        "dry-run preview recorded; live execution remains disabled in this version"
        if verdict == "pass"
        else "stop before live GitHub side effects and generate fallback evidence"
    )
    gates = []
    for stage, title, description in AUTO_REVIEW_STAGES:
        gates.append(
            AutoIssueFixReviewGate(
                stage=stage,
                title=title,
                verdict=verdict,
                summary=f"{description} Current mode is {config.mode}; automatic review is {config.auto_review}.",
                required_action=action,
            )
        )
    gates.append(
        AutoIssueFixReviewGate(
            stage="maintainer-trust",
            title="Maintainer trust review",
            verdict=verdict,
            summary="Check public PR-facing text for tool experiment notes before publication.",
            required_action=action,
        )
    )
    return tuple(gates)


def _review_gate_lines(review_gates: list[dict]) -> str:
    if not review_gates:
        return "- (none recorded)"
    return "\n".join(
        f"- `{item.get('stage', '-')}` {item.get('title', '')}: {item.get('verdict', '-')}"
        for item in review_gates
    )


def _changed_path_lines(paths) -> str:
    return "\n".join(f"- `{path}`" for path in paths) or "- (none recorded)"


def _validation_lines(tests) -> str:
    return "\n".join(
        f"- `{item.get('command', '-')}`: {item.get('status', '-')}" for item in tests
    ) or "- (not run)"


def review_gates_block_reason(review_gates: tuple[AutoIssueFixReviewGate, ...], max_review_repairs: int) -> str:
    for gate in review_gates:
        gate.validate()
        if gate.verdict == "block":
            return f"{gate.stage} review gate blocked the run"
        if gate.verdict == "needs_fix" and gate.repair_attempts >= max_review_repairs:
            return f"{gate.stage} review gate exceeded max review repairs"
    return ""


def render_evidence_templates(record: AutoIssueFixRunRecord, include_local_paths: bool = False) -> dict[str, str]:
    public_record = _public_record(record, include_local_paths)
    repo = public_record.get("repo") or "<repo>"
    issue = public_record.get("issue")
    issue_ref = f"#{issue}" if issue is not None else "(auto-discovered)"
    tests = public_record.get("tests") or []
    test_lines = _validation_lines(tests)
    fallback = public_record.get("fallback_reason") or ""
    fallback_block = f"\n\n## Fallback\n\nPR creation blocked: {fallback}\n" if fallback else ""
    status = public_record.get("status", "")
    pr_url = public_record.get("pr_url") or ""
    review_gates = public_record.get("review_gates") or []
    review_lines = _review_gate_lines(review_gates)

    run_record = f"""# Auto Issue Fix Run Record

## Summary

- Run ID: `{public_record['run_id']}`
- Mode: `{public_record['mode']}`
- Repository: `{repo}`
- Issue: `{issue_ref}`
- Status: `{status}`
- Workspace: `{public_record['workspace_path']}`
- Evidence directory: `{public_record['evidence_dir']}`
- PR URL: `{pr_url or '(none)'}`
- Automatic review: `{public_record.get('auto_review', 'required')}`
- Max review repairs: `{public_record.get('max_review_repairs', 2)}`
- Stage: `{public_record.get('stage') or '(none)'}`
- Branch: `{public_record.get('branch') or '(none)'}`
- Commit: `{public_record.get('commit') or '(none)'}`
- Baseline: `{public_record.get('baseline_status') or '(not recorded)'}`
- Workdir: `{portable_path(public_record.get('workdir') or '', '<workdir>', include_local_paths)}`

## Result

{public_record.get('summary') or '(none)'}

## Automatic Review Gates

{review_lines}

## Tests

{test_lines}
{fallback_block}
## Changed Paths

{_changed_path_lines(public_record.get('changed_paths', ()))}
"""

    if fallback:
        pr_body = f"""# PR-ready fallback

No pull request was created because the run was blocked before publication.

Repository: {repo}
Issue: {issue_ref}
Reason: {fallback}
"""
    else:
        pr_body = f"""## Summary

- Provides a focused candidate fix for the linked issue.
- Keeps the change scoped to the files listed below.

## Related Issue

Addresses {issue_ref}

## Validation

{test_lines}

## Scope

{_changed_path_lines(public_record.get('changed_paths', ()))}

## Notes for Maintainers

- This is a draft pull request for maintainer review.
- Please review the diff and validation results before considering merge.
"""

    formal_summary = f"""# RepoHarness Auto Issue Fix Formal Report Summary

This run is an Auto Issue Fix assisted workflow, not a claim that model output is trusted without governance. RepoHarness coordinates scoped file access, evidence generation, test gates, and PR preparation while preserving auditability.

- Repository: `{repo}`
- Issue: `{issue_ref}`
- Mode: `{public_record['mode']}`
- Status: `{status}`
- Evidence: `{public_record['evidence_dir']}`
- PR: `{pr_url or '(not created)'}`
- Automatic review: `{public_record.get('auto_review', 'required')}`
- Stage: `{public_record.get('stage') or '(none)'}`
- Branch: `{public_record.get('branch') or '(none)'}`

## Review Gates

{review_lines}
"""

    rendered = {
        "run-record.md": redact_text(run_record),
        "pr-body.md": redact_text(pr_body),
        "formal-report-summary.md": redact_text(formal_summary),
        "run-record.json": json.dumps(public_record, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
    }
    if fallback:
        rendered["pr-ready-fallback.md"] = redact_text(
            f"""# PR-ready fallback

Auto Issue Fix stopped before creating a pull request.

- Repository: `{repo}`
- Issue: `{issue_ref}`
- Reason: {fallback}
- Evidence: `{public_record['evidence_dir']}`
"""
        )
    return rendered


def write_evidence(record: AutoIssueFixRunRecord, include_local_paths: bool = False) -> dict[str, Path]:
    evidence_dir = Path(record.evidence_dir)
    evidence_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for name, content in render_evidence_templates(record, include_local_paths=include_local_paths).items():
        path = evidence_dir / name
        path.write_text(content, encoding="utf-8")
        written[name] = path
    public_record = _public_record(record, include_local_paths)
    reviews_dir = evidence_dir / "reviews"
    reviews_dir.mkdir(parents=True, exist_ok=True)
    decisions = []
    for gate in public_record.get("review_gates", ()):
        stage = str(gate.get("stage", "unknown"))
        json_path = reviews_dir / f"review-{stage}.json"
        md_path = reviews_dir / f"review-{stage}.md"
        json_path.write_text(json.dumps(gate, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
        md_path.write_text(
            redact_text(
                f"""# {gate.get('title', stage)}

- Stage: `{stage}`
- Verdict: `{gate.get('verdict', '-')}`
- Required action: {gate.get('required_action') or '(none)'}

{gate.get('summary') or ''}
"""
            ),
            encoding="utf-8",
        )
        written[str(json_path.relative_to(evidence_dir))] = json_path
        written[str(md_path.relative_to(evidence_dir))] = md_path
        decisions.append(
            {
                "run_id": public_record.get("run_id"),
                "stage": stage,
                "verdict": gate.get("verdict"),
                "required_action": gate.get("required_action", ""),
            }
        )
    decision_log_path = evidence_dir / "decision-log.jsonl"
    decision_log_path.write_text(
        "".join(json.dumps(item, ensure_ascii=False, sort_keys=True) + "\n" for item in decisions),
        encoding="utf-8",
    )
    written["decision-log.jsonl"] = decision_log_path
    checkpoint_path = evidence_dir / "checkpoint.json"
    checkpoint = {
        "run_id": public_record.get("run_id"),
        "mode": public_record.get("mode"),
        "status": public_record.get("status"),
        "stage": public_record.get("stage") or "",
        "branch": public_record.get("branch") or "",
        "commit": public_record.get("commit") or "",
        "pr_url": public_record.get("pr_url") or "",
        "resume_from": public_record.get("resume_from") or "",
        "next_action": _checkpoint_next_action(public_record),
    }
    checkpoint_path.write_text(json.dumps(checkpoint, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    written["checkpoint.json"] = checkpoint_path
    return written


def _checkpoint_next_action(public_record: dict) -> str:
    status = public_record.get("status")
    if status == "completed":
        return "draft PR created; review upstream PR and evidence"
    if status == "paused":
        return "resume after review-gated confirmation"
    if status in {"blocked", "failed"}:
        return "inspect fallback evidence before rerunning"
    if status == "planned":
        return "dry-run preview recorded; rerun without --dry-run for live execution"
    return "inspect evidence and checkpoint before continuing"


def write_evidence_file(evidence_dir: Path, name: str, content: str, include_local_paths: bool = False) -> Path:
    path = evidence_dir / name
    path.parent.mkdir(parents=True, exist_ok=True)
    text = redact_text(str(content))
    if not include_local_paths:
        text = text.replace(str(evidence_dir), "<evidence_dir>")
    path.write_text(text, encoding="utf-8")
    return path


def write_json_evidence(evidence_dir: Path, name: str, payload: dict, include_local_paths: bool = False) -> Path:
    return write_evidence_file(
        evidence_dir,
        name,
        json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        include_local_paths=include_local_paths,
    )


def infer_test_commands(repo_root: Path) -> tuple[str, ...]:
    if (repo_root / "pyproject.toml").exists() or (repo_root / "pytest.ini").exists():
        if (repo_root / "tests").exists():
            return ("python -m pytest -q",)
    if (repo_root / "package.json").exists():
        return ("npm test",)
    if (repo_root / "go.mod").exists():
        return ("go test ./...",)
    if (repo_root / "Cargo.toml").exists():
        return ("cargo test",)
    return ()


def run_shell_command(command: str, cwd: Path, timeout: int = 600) -> CommandResult:
    completed = subprocess.run(
        command,
        cwd=str(cwd),
        text=True,
        capture_output=True,
        shell=True,
        timeout=timeout,
        check=False,
    )
    return CommandResult(
        args=(command,),
        cwd=str(cwd.resolve()),
        returncode=int(completed.returncode),
        stdout=completed.stdout or "",
        stderr=completed.stderr or "",
    )


def run_test_commands(commands: tuple[str, ...], cwd: Path, log_path: Path) -> list[dict]:
    results = []
    blocks = []
    for command in commands:
        result = run_shell_command(command, cwd=cwd)
        status = "passed" if result.ok else "failed"
        results.append({"command": command, "status": status, "returncode": result.returncode})
        blocks.append(
            f"$ {command}\nreturncode: {result.returncode}\n\nSTDOUT\n{result.stdout}\n\nSTDERR\n{result.stderr}\n"
        )
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text("\n\n".join(blocks) if blocks else "(no test command inferred or provided)\n", encoding="utf-8")
    return results


def changed_paths(cwd: Path) -> tuple[str, ...]:
    result = run_command(["git", "diff", "--name-only"], cwd=cwd)
    require_ok(result, "git diff --name-only failed")
    return tuple(line.strip() for line in result.stdout.splitlines() if line.strip())


def git_diff(cwd: Path) -> str:
    result = run_command(["git", "diff", "--binary"], cwd=cwd)
    require_ok(result, "git diff failed")
    return result.stdout


def scan_diff_gate(cwd: Path, paths: tuple[str, ...], diff_text: str) -> str:
    if not paths:
        return "no changed files"
    blocked_prefixes = (".git/", ".repo-harness/", ".venv/", "venv/", "node_modules/")
    for path in paths:
        normalized = path.replace("\\", "/")
        if normalized.startswith(blocked_prefixes):
            return f"diff gate blocked generated or internal path: {path}"
    diff_check = run_command(["git", "diff", "--check"], cwd=cwd)
    if not diff_check.ok:
        return "git diff --check failed"
    if redact_text(diff_text) != diff_text:
        return "secret-shaped content detected in diff"
    return ""


def build_rule_review_gates(
    config: AutoIssueFixConfig,
    *,
    issue: AutoIssueFixIssue | None,
    diff_block: str,
    maintainer_trust_block: str = "",
    tests: list[dict],
    changed: tuple[str, ...],
) -> tuple[AutoIssueFixReviewGate, ...]:
    gates = []
    has_failed_tests = any(item.get("status") == "failed" for item in tests)
    for stage, title, description in AUTO_REVIEW_STAGES:
        verdict = "pass"
        action = "continue"
        summary = description
        if stage == "task" and issue is None:
            verdict = "block"
            action = "select an issue before running Auto Issue Fix"
        elif stage == "diff" and diff_block:
            verdict = "block"
            action = diff_block
            summary = f"{description} {diff_block}"
        elif stage == "tests" and not tests:
            verdict = "block"
            action = "provide --test-command or add a detectable project test command before PR creation"
            summary = f"{description} No validation command was provided or inferred."
        elif stage == "tests" and has_failed_tests:
            verdict = "block"
            action = "fix failing validation commands before PR creation"
            summary = f"{description} One or more validation commands failed."
        elif stage == "pr-readiness" and not changed:
            verdict = "block"
            action = "produce a non-empty diff before PR creation"
            summary = f"{description} No changed files were found."
        gates.append(
            AutoIssueFixReviewGate(
                stage=stage,
                title=title,
                verdict=verdict,
                summary=summary,
                required_action=action,
            )
        )
    gates.append(
        AutoIssueFixReviewGate(
            stage="maintainer-trust",
            title="Maintainer trust review",
            verdict="block" if maintainer_trust_block else "pass",
            summary=maintainer_trust_block
            or "Public PR title, body, commit message, and branch are maintainer-facing.",
            required_action=maintainer_trust_block or "continue",
        )
    )
    return tuple(gates)


def score_issue(issue: AutoIssueFixIssue) -> int:
    text = f"{issue.title}\n{issue.body}".lower()
    labels = {label.lower() for label in issue.labels}
    score = 0
    if labels & {"bug", "type: bug", "test", "tests", "good first issue"}:
        score += 3
    if any(word in text for word in ("reproduce", "repro", "steps", "expected", "actual")):
        score += 3
    if any(word in text for word in ("pytest", "npm test", "go test", "cargo test", "test")):
        score += 2
    if not issue.assignees:
        score += 1
    if any(word in text for word in ("aws", "gcp", "azure", "api key", "credential", "database")):
        score -= 5
    if any(word in text for word in ("refactor", "rewrite", "architecture", "design proposal")):
        score -= 4
    return score


def discover_issue(config: AutoIssueFixConfig, backend: GhCliBackend, evidence_dir: Path) -> AutoIssueFixIssue:
    repos = [normalize_repo(config.repo)] if config.repo else []
    if not repos:
        repos = backend.search_repos(limit=10)
    candidates = []
    for repo in repos[:10]:
        for issue in backend.issue_list(repo, limit=20):
            candidates.append((score_issue(issue), issue))
    candidates.sort(key=lambda item: item[0], reverse=True)
    payload = [{"score": score, **issue.to_dict()} for score, issue in candidates]
    write_json_evidence(evidence_dir, "issue-selection.json", {"candidates": payload})
    lines = ["# Issue Selection", ""]
    for score, issue in candidates[:10]:
        lines.append(f"- score={score} `{issue.repo}#{issue.number}` {issue.title}")
    write_evidence_file(evidence_dir, "issue-selection.md", "\n".join(lines) + "\n")
    if not candidates or candidates[0][0] < 1:
        raise RuntimeError("no suitable issue found during discovery")
    return candidates[0][1]


