"""Auto Issue Fix orchestration primitives.

Auto Issue Fix is a governed workflow layer for turning GitHub issues into auditable
candidate fixes. It supports safe previews and live draft PR execution while
keeping public PR text maintainer-facing and local evidence auditable.
"""

